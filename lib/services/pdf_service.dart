import 'dart:typed_data';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:invoicehub/models/profile.dart';
import 'package:invoicehub/models/business_models.dart';
import 'package:invoicehub/models/invoice_model.dart';

class PdfService {
  // Match these to AppColors.primary / AppColors.secondary so the PDF
  // looks like the rest of the app.
  static final PdfColor _brandPrimary = PdfColor.fromHex('#3D5AFE');
  static final PdfColor _brandSecondary = PdfColor.fromHex('#00BFA6');
  static final PdfColor _brandPrimaryDark = PdfColor.fromHex('#2A3EB1');

  static Future<Uint8List> generateInvoicePdf({
    required Profile shop,
    required Customer? customer,
    required Invoice invoice,
    required List<InvoiceItem> items,
    Uint8List? signatureBytes,
    PdfPageFormat format = PdfPageFormat.a4,
  }) async {
    final fontBase = await PdfGoogleFonts.notoSansRegular();
    final fontBold = await PdfGoogleFonts.notoSansBold();

    final pdf = pw.Document(
      theme: pw.ThemeData.withFont(
        base: fontBase,
        bold: fontBold,
      ),
    );
    final signatureImage = signatureBytes != null ? pw.MemoryImage(signatureBytes) : null;

    pdf.addPage(
      pw.MultiPage(
        pageFormat: format,
        margin: const pw.EdgeInsets.fromLTRB(28, 24, 28, 24),
        header: (context) => context.pageNumber == 1
            ? pw.SizedBox.shrink()
            : pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 8),
                child: pw.Text(
                  'Invoice ${invoice.invoiceNumber} (contd.)',
                  style: pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
                ),
              ),
        footer: (context) => pw.Padding(
          padding: const pw.EdgeInsets.only(top: 8),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text('Generated by InvoiceHub', style: pw.TextStyle(fontSize: 8, color: PdfColors.grey500)),
              pw.Text(
                'Page ${context.pageNumber} of ${context.pagesCount}',
                style: pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
              ),
            ],
          ),
        ),
        build: (pw.Context context) {
          return [
            _buildHeader(shop, invoice),
            pw.SizedBox(height: 16),
            _buildInfoSection(shop, customer, invoice),
            pw.SizedBox(height: 16),
            _buildItemsTable(items),
            pw.Spacer(),
            _buildTotalSection(invoice),
            pw.SizedBox(height: 16),
            _buildTermsAndSignature(shop, customer, signatureImage),
          ];
        },
      ),
    );

    return pdf.save();
  }

  static pw.Widget _buildHeader(Profile shop, Invoice invoice) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.symmetric(horizontal: 20, vertical: 16),
      decoration: pw.BoxDecoration(
        borderRadius: pw.BorderRadius.circular(6),
        gradient: pw.LinearGradient(
          colors: [_brandPrimary, _brandSecondary],
          begin: pw.Alignment.topLeft,
          end: pw.Alignment.bottomRight,
        ),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Center(
            child: pw.Text(
              '|| Jay Swaminarayan ||',
              style: pw.TextStyle(
                fontSize: 10,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.white,
                letterSpacing: 1.2,
              ),
            ),
          ),
          pw.SizedBox(height: 12),
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Expanded(
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      shop.shopName ?? 'My Shop',
                      style: pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
                    ),
                    if (shop.address != null)
                      pw.Padding(
                        padding: const pw.EdgeInsets.only(top: 3),
                        child: pw.Text(shop.address!, style: const pw.TextStyle(fontSize: 10, color: PdfColors.white)),
                      ),
                    if (shop.gstNumber != null)
                      pw.Padding(
                        padding: const pw.EdgeInsets.only(top: 5),
                        child: pw.Text(
                          'GSTIN: ${shop.gstNumber}',
                          style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
                        ),
                      ),
                  ],
                ),
              ),
              pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.end,
                children: [
                  pw.Text(
                    'TAX INVOICE',
                    style: pw.TextStyle(fontSize: 22, color: PdfColors.white, fontWeight: pw.FontWeight.bold),
                  ),
                  pw.SizedBox(height: 8),
                  pw.Text('Invoice No: ${invoice.invoiceNumber}', style: const pw.TextStyle(fontSize: 10, color: PdfColors.white)),
                  pw.Text('Date: ${DateFormat('dd-MM-yyyy').format(invoice.invoiceDate)}', style: const pw.TextStyle(fontSize: 10, color: PdfColors.white)),
                  if (shop.mobile != null) ...[
                    pw.SizedBox(height: 4),
                    pw.Text('Phone: ${shop.mobile}', style: const pw.TextStyle(fontSize: 10, color: PdfColors.white)),
                  ],
                  if (shop.ownerName != null) ...[
                    pw.SizedBox(height: 2),
                    pw.Text(
                      'Owner: ${shop.ownerName}',
                      style: pw.TextStyle(fontSize: 9, fontStyle: pw.FontStyle.italic, color: PdfColors.white),
                    ),
                  ],
                ],
              ),
            ],
          ),
        ],
      ),
    );
  }

