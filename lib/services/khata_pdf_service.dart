  /// Generate CA-Style Individual Customer Ledger PDF
  static Future<Uint8List> generateCustomerLedgerPdf({
    required Profile shop,
    required Customer customer,
    required List<KhataTransaction> transactions,
    String? dateRangeText,
    PdfPageFormat format = PdfPageFormat.a4,
  }) async {
    final fontBase = await PdfGoogleFonts.notoSansRegular();
    final fontBold = await PdfGoogleFonts.notoSansBold();

    final pdf = pw.Document(
      theme: pw.ThemeData.withFont(
        base: fontBase,
        bold: fontBold,
      ),
    );

    // Calculate Totals
    double totalGave = 0.0;
    double totalGot = 0.0;
    for (final tx in transactions) {
      if (tx.isGave) {
        totalGave += tx.amount;
      } else {
        totalGot += tx.amount;
      }
    }
    final netBalance = totalGave - totalGot;

    // Chronological transactions for table running balance
    final chronoTxs = List<KhataTransaction>.from(transactions)
      ..sort((a, b) => a.transactionDate.compareTo(b.transactionDate));

    final shopNameStr = shop.shopName ?? 'My Shop';

    pdf.addPage(
      pw.MultiPage(
        pageFormat: format,
        margin: const pw.EdgeInsets.fromLTRB(28, 24, 28, 24),
        header: (context) => context.pageNumber == 1
            ? pw.SizedBox.shrink()
            : pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 8),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text(
                      'Khata Statement - ${customer.customerName}',
                      style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
                    ),
                    pw.Text(
                      'Shop: $shopNameStr',
                      style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
                    ),
                  ],
                ),
              ),
        footer: (context) => pw.Padding(
          padding: const pw.EdgeInsets.only(top: 8),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text('Generated by InvoiceHub - Khata Book Module', style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500)),
              pw.Text(
                'Page ${context.pageNumber} of ${context.pagesCount}',
                style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
              ),
            ],
          ),
        ),
        build: (pw.Context context) {
          return [
            _buildHeader(shop, 'CUSTOMER ACCOUNT LEDGER STATEMENT'),
            pw.SizedBox(height: 14),
            _buildCustomerAndDateSection(shop, customer, dateRangeText),
            pw.SizedBox(height: 14),
            _buildFinancialSummaryCards(totalGave, totalGot, netBalance),
            pw.SizedBox(height: 16),
            _buildTransactionLedgerTable(chronoTxs),
            pw.Spacer(),
            _buildSignatureBlock(shop),
          ];
        },
      ),
    );

    return pdf.save();
  }

  /// Generate CA-Style Shop-wide Financial Khata Summary PDF
  static Future<Uint8List> generateShopKhataReportPdf({
    required Profile shop,
    required List<CustomerKhataSummary> customerSummaries,
    String? dateRangeText,
    PdfPageFormat format = PdfPageFormat.a4,
  }) async {
    final fontBase = await PdfGoogleFonts.notoSansRegular();
    final fontBold = await PdfGoogleFonts.notoSansBold();

    final pdf = pw.Document(
      theme: pw.ThemeData.withFont(
        base: fontBase,
        bold: fontBold,
      ),
    );

    double totalReceivables = 0.0;
    double totalPayables = 0.0;
    double overallGave = 0.0;
    double overallGot = 0.0;

    for (final s in customerSummaries) {
      overallGave += s.totalGave;
      overallGot += s.totalGot;
      if (s.netBalance > 0) {
        totalReceivables += s.netBalance;
      } else if (s.netBalance < 0) {
        totalPayables += s.netBalance.abs();
      }
    }

    final shopNameStr = shop.shopName ?? 'My Shop';

    pdf.addPage(
      pw.MultiPage(
        pageFormat: format,
        margin: const pw.EdgeInsets.fromLTRB(28, 24, 28, 24),
        header: (context) => context.pageNumber == 1
            ? pw.SizedBox.shrink()
            : pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 8),
                child: pw.Text(
                  'Shop Khata Financial Summary - $shopNameStr',
                  style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
                ),
              ),
        footer: (context) => pw.Padding(
          padding: const pw.EdgeInsets.only(top: 8),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text('Generated by InvoiceHub - Accounting Report', style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500)),
              pw.Text(
                'Page ${context.pageNumber} of ${context.pagesCount}',
                style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
              ),
            ],
          ),
        ),
        build: (pw.Context context) {
          return [
            _buildHeader(shop, 'SHOP KHATA FINANCIAL SUMMARY (CA REPORT)'),
            pw.SizedBox(height: 14),
            _buildShopReportMeta(shop, dateRangeText, customerSummaries.length),
            pw.SizedBox(height: 14),
            _buildShopSummaryCards(totalReceivables, totalPayables, overallGave, overallGot),
            pw.SizedBox(height: 16),
            _buildCustomerSummariesTable(customerSummaries),
            pw.Spacer(),
            _buildSignatureBlock(shop),
          ];
        },
      ),
    );

    return pdf.save();
  }

