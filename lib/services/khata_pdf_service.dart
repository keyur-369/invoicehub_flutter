  static pw.Widget _buildTransactionLedgerTable(List<KhataTransaction> chronoTxs) {
    double runningBalance = 0.0;

    final tableRows = <pw.TableRow>[
      // Table Header
      pw.TableRow(
        decoration: pw.BoxDecoration(color: _brandPrimary),
        children: [
          _buildTableCell('Date', isHeader: true, flex: 2),
          _buildTableCell('Details / Ref', isHeader: true, flex: 3),
          _buildTableCell('Mode', isHeader: true, flex: 2),
          _buildTableCell('You Gave (Dr)', isHeader: true, alignRight: true, flex: 2),
          _buildTableCell('You Got (Cr)', isHeader: true, alignRight: true, flex: 2),
          _buildTableCell('Balance (Rs)', isHeader: true, alignRight: true, flex: 2),
        ],
      ),
    ];

    for (int i = 0; i < chronoTxs.length; i++) {
      final tx = chronoTxs[i];
      if (tx.isGave) {
        runningBalance += tx.amount;
      } else {
        runningBalance -= tx.amount;
      }

      final isEven = i % 2 == 0;
      final rowBg = isEven ? PdfColors.white : _greyLight;

      String details = tx.notes ?? '';
      if (tx.invoiceId != null && tx.invoiceId!.isNotEmpty) {
        details = details.isEmpty ? 'Invoice Ref' : '$details (Inv)';
      }

      String balText = '';
      if (runningBalance > 0) {
        balText = '${runningBalance.toStringAsFixed(0)} Dr';
      } else if (runningBalance < 0) {
        balText = '${runningBalance.abs().toStringAsFixed(0)} Cr';
      } else {
        balText = '0 (Settled)';
      }

      tableRows.add(
        pw.TableRow(
          decoration: pw.BoxDecoration(color: rowBg),
          children: [
            _buildTableCell(DateFormat('dd/MM/yyyy').format(tx.transactionDate), flex: 2),
            _buildTableCell(details.isEmpty ? '-' : details, flex: 3),
            _buildTableCell(tx.paymentMode, flex: 2),
            _buildTableCell(tx.isGave ? 'Rs. ${tx.amount.toStringAsFixed(0)}' : '-', alignRight: true, flex: 2, textColor: tx.isGave ? _gaveRed : null),
            _buildTableCell(tx.isGot ? 'Rs. ${tx.amount.toStringAsFixed(0)}' : '-', alignRight: true, flex: 2, textColor: tx.isGot ? _gotGreen : null),
            _buildTableCell(balText, alignRight: true, flex: 2, isBold: true),
          ],
        ),
      );
    }

    if (chronoTxs.isEmpty) {
      tableRows.add(
        pw.TableRow(
          children: [
            pw.Padding(
              padding: const pw.EdgeInsets.all(12),
              child: pw.Center(
                child: pw.Text('No ledger transactions recorded in this period.', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
              ),
            ),
          ],
        ),
      );
    }

    return pw.Table(
      border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
      children: tableRows,
    );
  }

  static pw.Widget _buildCustomerSummariesTable(List<CustomerKhataSummary> customerSummaries) {
    final tableRows = <pw.TableRow>[
      // Table Header
      pw.TableRow(
        decoration: pw.BoxDecoration(color: _brandPrimary),
        children: [
          _buildTableCell('S.No', isHeader: true, flex: 1),
          _buildTableCell('Customer Name', isHeader: true, flex: 4),
          _buildTableCell('Mobile', isHeader: true, flex: 3),
          _buildTableCell('Total Gave (Dr)', isHeader: true, alignRight: true, flex: 3),
          _buildTableCell('Total Got (Cr)', isHeader: true, alignRight: true, flex: 3),
          _buildTableCell('Net Status', isHeader: true, alignRight: true, flex: 3),
        ],
      ),
    ];

    for (int i = 0; i < customerSummaries.length; i++) {
      final s = customerSummaries[i];
      final isEven = i % 2 == 0;
      final rowBg = isEven ? PdfColors.white : _greyLight;

      String netStr = 'Settled';
      PdfColor netCol = PdfColors.grey800;
      if (s.netBalance > 0) {
        netStr = 'Rs. ${s.netBalance.toStringAsFixed(0)} (Get)';
        netCol = _gaveRed;
      } else if (s.netBalance < 0) {
        netStr = 'Rs. ${s.netBalance.abs().toStringAsFixed(0)} (Give)';
        netCol = _gotGreen;
      }

      tableRows.add(
        pw.TableRow(
          decoration: pw.BoxDecoration(color: rowBg),
          children: [
            _buildTableCell('${i + 1}', flex: 1),
            _buildTableCell(s.customer.customerName, flex: 4, isBold: true),
            _buildTableCell(s.customer.mobile ?? '-', flex: 3),
            _buildTableCell('Rs. ${s.totalGave.toStringAsFixed(0)}', alignRight: true, flex: 3, textColor: _gaveRed),
            _buildTableCell('Rs. ${s.totalGot.toStringAsFixed(0)}', alignRight: true, flex: 3, textColor: _gotGreen),
            _buildTableCell(netStr, alignRight: true, flex: 3, isBold: true, textColor: netCol),
          ],
        ),
      );
    }

    return pw.Table(
      border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
      children: tableRows,
    );
  }

  static pw.Widget _buildTableCell(
    String text, {
    bool isHeader = false,
    bool alignRight = false,
    bool isBold = false,
    int flex = 1,
    PdfColor? textColor,
  }) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 5),
      child: pw.Text(
        text,
        textAlign: alignRight ? pw.TextAlign.right : pw.TextAlign.left,
        style: pw.TextStyle(
          fontSize: isHeader ? 8 : 8,
          fontWeight: (isHeader || isBold) ? pw.FontWeight.bold : pw.FontWeight.normal,
          color: isHeader ? PdfColors.white : (textColor ?? PdfColors.black),
        ),
      ),
    );
  }

